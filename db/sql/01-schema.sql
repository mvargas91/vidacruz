DROP TABLE IF EXISTS patient;

CREATE TABLE IF NOT EXISTS patient (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name          VARCHAR(255)  NOT NULL,
    age                INTEGER,
    heart_rate         INTEGER,
    systolic_pressure  INTEGER,
    diastolic_pressure INTEGER,
    sp_o_two           INTEGER,
    temperature        NUMERIC(4,2),
    ache               INTEGER,
    gcs                INTEGER,
    description        TEXT,

    CONSTRAINT chk_patient_age         CHECK (age IS NULL OR age BETWEEN 0 AND 150),
    CONSTRAINT chk_patient_heart_rate  CHECK (heart_rate IS NULL OR heart_rate >= 0),
    CONSTRAINT chk_patient_systolic    CHECK (systolic_pressure IS NULL OR systolic_pressure >= 0),
    CONSTRAINT chk_patient_diastolic   CHECK (diastolic_pressure IS NULL OR diastolic_pressure >= 0),
    CONSTRAINT chk_patient_sp_o_two    CHECK (sp_o_two IS NULL OR sp_o_two BETWEEN 0 AND 100),
    CONSTRAINT chk_patient_ache        CHECK (ache IS NULL OR ache BETWEEN 0 AND 10),
    CONSTRAINT chk_patient_gcs         CHECK (gcs IS NULL OR gcs BETWEEN 3 AND 15)
);

COMMENT ON TABLE  patient                    IS 'Pacientes y sus signos vitales';
COMMENT ON COLUMN patient.heart_rate         IS 'Frecuencia cardiaca (lpm)';
COMMENT ON COLUMN patient.systolic_pressure  IS 'Presion sistolica (mmHg)';
COMMENT ON COLUMN patient.diastolic_pressure IS 'Presion diastolica (mmHg)';
COMMENT ON COLUMN patient.sp_o_two           IS 'Saturacion de oxigeno SpO2 (%)';
COMMENT ON COLUMN patient.temperature        IS 'Temperatura corporal (C)';
COMMENT ON COLUMN patient.ache               IS 'Nivel de dolor (escala 0-10)';
COMMENT ON COLUMN patient.gcs                IS 'Escala de coma de Glasgow (3-15)';